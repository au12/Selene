// Build shared/glyphs.js: per-font glyph outlines (1000 units/em, y down, baseline at 0)
import fs from 'fs';
import opentype from 'opentype.js';
const fonts = {
  brand: 'node_modules/@fontsource/michroma/files/michroma-latin-400-normal.woff',
  label: 'node_modules/@fontsource/saira/files/saira-latin-600-normal.woff',
  labelB: 'node_modules/@fontsource/saira/files/saira-latin-700-normal.woff',
  cond: 'node_modules/@fontsource/saira-condensed/files/saira-condensed-latin-600-normal.woff',
  serif: 'node_modules/@fontsource/libre-caslon-text/files/libre-caslon-text-latin-700-normal.woff',
};
const charset = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789·-/.:°\'&+';
const out = {};
for (const [key, file] of Object.entries(fonts)) {
  const buf = fs.readFileSync(file);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const scale = 1000 / font.unitsPerEm;
  const g = {};
  for (const ch of charset) {
    const glyph = font.charToGlyph(ch);
    const p = glyph.getPath(0, 0, 1000);
    // compact path: round to integers
    const d = p.commands.map(c => {
      const r = v => Math.round(v);
      switch (c.type) {
        case 'M': return `M${r(c.x)} ${r(c.y)}`;
        case 'L': return `L${r(c.x)} ${r(c.y)}`;
        case 'Q': return `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
        case 'C': return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
        case 'Z': return 'Z';
      }
    }).join('');
    g[ch] = [Math.round(glyph.advanceWidth * scale), d];
  }
  const capH = Math.round((font.tables.os2.sCapHeight || 700) * scale);
  out[key] = { capH, g };
  console.log(key, (font.names.fullName||font.names.windows?.fullName||{}).en, 'capH', capH, 'size', JSON.stringify(g).length);
}
const js = `/* Generated by tools/gen_glyphs.mjs from OFL fonts (Michroma, Saira, Saira Condensed, Libre Caslon Text). Do not edit. */\n(function(r,f){if(typeof module==='object'&&module.exports)module.exports=f();else r.SeleneGlyphs=f();})(typeof self!=='undefined'?self:this,function(){return ${JSON.stringify(out)};});\n`;
fs.writeFileSync('/home/claude/selene/shared/glyphs.js', js);
console.log('glyphs.js bytes', js.length);
