// Generates firmware/components/selene/segments.h from the canonical JS segment order.
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire(import.meta.url);
const M = require('../shared/module.js');
const F = require('../shared/faces.js');
const ids = M.SEGMENT_IDS, idx = (s) => ids.indexOf(s);
// every face segment must exist in the canonical list
for (const f of F.ids) for (const s of F.build(f).segs) if (idx(s.id) < 0) throw new Error(`${f}: unknown segment ${s.id}`);
const c = (name, id) => `constexpr int ${name} = ${idx(id)};`;
const lines = [
  '#pragma once', '// Generated by tools/gen_segments.mjs — logical segment indices shared by all faces. Do not edit.',
  'namespace esphome {', 'namespace selene {',
  `constexpr int SEG_COUNT = ${ids.length};`, `constexpr int SEG_WORDS = ${Math.ceil(ids.length / 32)};`,
  c('SEG_X', 'x000') + '  // dot matrix: + c*35 + r*5 + k', c('SEG_XDP', 'xdp'),
  c('SEG_T', 't0a') + '  // small digits: + n*7 + (a..g)', c('SEG_TDASH', 'tdash'), c('SEG_TCOL', 'tcol'),
  c('SEG_B', 'b0a') + '  // big digits: + n*7 + (a..g)', c('SEG_B5W', 'b5w'), c('SEG_BCOL', 'bcol'),
  c('SEG_PM', 'pm'), c('SEG_H24', 'h24'), c('SEG_ALM', 'alm'), c('SEG_CHM', 'chm'),
  c('SEG_LAGE', 'lage'), c('SEG_LMOON', 'lmoon'), c('SEG_LRISE', 'lrise'), c('SEG_LSET', 'lset'),
  c('SEG_P', 'p0') + '  // moon phase slots 0..8', c('SEG_H', 'h0') + '  // hour-angle markers 0..12',
  c('SEG_SUNE', 'sune'), c('SEG_SUNW', 'sunw'), c('SEG_R', 'r0') + '  // reflections 0..8 (optional)',
  c('SEG_Q', 'q0') + '  // seconds ring 0..59 (optional)',
  '}  // namespace selene', '}  // namespace esphome', '',
];
fs.writeFileSync('firmware/components/selene/segments.h', lines.join('\n'));
console.log('segments.h:', ids.length, 'segments');
