import { chromium } from 'playwright';
import path from 'path';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 3 })).newPage();
await page.goto('file://' + path.resolve('dist/index.html')); await page.waitForTimeout(1000);
await page.mouse.move(1300, 960); await page.waitForTimeout(600);
const r = await (await page.$('.device-wrap')).boundingBox();
const u = r.width / 1000, Y = (y) => r.y + (y - 240) * u, X = (x) => r.x + x * u;
await page.screenshot({ path: process.argv[2], clip: { x: X(225), y: Math.max(0, Y(-70)), width: 550 * u, height: Y(420) - Math.max(0, Y(-70)) } });
await page.screenshot({ path: process.argv[3], clip: { x: X(225), y: Y(1140), width: 550 * u, height: 220 * u } });
await browser.close();
