"""Pack rendered face layers (tools/render_faces.mjs) into C++ headers for the ESPHome component.

    python tools/pack_faces.py build/faces firmware/components/selene [--preview build/preview]

Output per face: face_<id>.h with
  * background: RGB565 (ordered-dithered) for the visible dial circle only, row spans
  * sprites:    per logical segment bbox + interleaved [body, aura] 8-bit coverage
  * colors:     lit colour and aura colour per segment class (lcd / mg)
"""
import base64
import json
import math
import sys
from pathlib import Path

import lz4.block
import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
SEG_IDS = None


def seg_ids():
    import subprocess
    out = subprocess.check_output(['node', '-e', "console.log(JSON.stringify(require('./shared/module.js').SEGMENT_IDS))"],
                                  cwd=Path(__file__).parent.parent)
    return json.loads(out)


BAYER4 = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], dtype=np.float32) / 16.0 - 0.5


def to565(rgb):
    """rgb: HxWx3 uint8 -> HxW uint16 with ordered dithering"""
    h, w, _ = rgb.shape
    th = np.tile(BAYER4, (h // 4 + 1, w // 4 + 1))[:h, :w]
    f = rgb.astype(np.float32)
    r = np.clip(np.floor(f[..., 0] / 255 * 31 + 0.5 + th), 0, 31).astype(np.uint16)
    g = np.clip(np.floor(f[..., 1] / 255 * 63 + 0.5 + th), 0, 63).astype(np.uint16)
    b = np.clip(np.floor(f[..., 2] / 255 * 31 + 0.5 + th), 0, 31).astype(np.uint16)
    return (r << 11) | (g << 5) | b


def hex565(color):
    c = color.lstrip('#')
    r, g, b = int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3), (r, g, b)


def spans(size):
    rows = []
    c = size / 2
    for y in range(size):
        dy = y + 0.5 - c
        half = math.sqrt(max(0.0, c * c - dy * dy))
        x0 = max(0, int(math.floor(c - half)))
        x1 = min(size, int(math.ceil(c + half)))
        rows.append((x0, x1 - x0))
    return rows


def c_string(data: bytes, per_line=160):
    """Compact C string literal: printable bytes as-is, others as 3-digit octal escapes."""
    lines, cur, n = [], [], 0
    for b in data:
        if 32 <= b < 127 and b not in (34, 63, 92):  # not '"', '?', '\\'
            cur.append(chr(b)); n += 1
        else:
            cur.append('\\%03o' % b); n += 4
        if n >= per_line:
            lines.append('"' + ''.join(cur) + '"'); cur, n = [], 0
    if cur:
        lines.append('"' + ''.join(cur) + '"')
    return '\n'.join(lines) if lines else '""'


def lz4c(data: bytes) -> bytes:
    return lz4.block.compress(data, mode='high_compression', compression=12, store_size=False)


def pack(face_dir: Path, out_dir: Path, preview_dir: Path | None):
    ids = seg_ids()
    index = {s: i for i, s in enumerate(ids)}
    out_dir.mkdir(parents=True, exist_ok=True)
    names = []
    for meta_path in sorted(face_dir.glob('*_segs.json')):
        meta = json.loads(meta_path.read_text())
        fid, size = meta['id'], meta['size']
        bg = np.asarray(Image.open(face_dir / f'{fid}_bg.png').convert('RGB'))
        bg565 = to565(bg)
        rows = spans(size)
        bg_bytes = bytearray()
        row_tab = []
        for y, (x0, n) in enumerate(rows):
            row_tab.append((len(bg_bytes) // 2, x0, n))
            bg_bytes += bg565[y, x0:x0 + n].astype('<u2').tobytes()
        sprites = [None] * len(ids)
        masks = bytearray()
        for s in meta['segs']:
            i = index[s['id']]
            body = np.frombuffer(base64.b64decode(s['body']), dtype=np.uint8)
            aura = np.frombuffer(base64.b64decode(s['aura']), dtype=np.uint8)
            inter = np.empty(body.size * 2, dtype=np.uint8)
            inter[0::2] = body
            inter[1::2] = aura
            sprites[i] = (s['x'], s['y'], s['w'], s['h'], len(masks), 0 if s['cls'] == 'lcd' else 1)
            masks += inter.tobytes()
        on = {k: hex565(v) for k, v in meta['colors'].items()}
        au = {k: hex565(v['color']) for k, v in meta['aura'].items()}
        bg_z, masks_z = lz4c(bytes(bg_bytes)), lz4c(bytes(masks))
        name = f'face_{fid}'
        names.append((fid, meta['name'], name))
        hdr = [
            '#pragma once',
            f'// Generated by tools/pack_faces.py from shared/faces.js ({fid}). Do not edit.',
            '#include "face_types.h"',
            'namespace esphome {', 'namespace selene {', 'namespace ' + name + ' {',
            f'alignas(4) static const char BG[] =\n{c_string(bg_z)};',
            'static const RowSpan ROWS[%d] = {%s};' % (size, ','.join('{%d,%d,%d}' % r for r in row_tab)),
            'static const SpriteDef SPRITES[%d] = {%s};' % (len(ids), ','.join(
                '{%d,%d,%d,%d,%d,%d}' % sp if sp else '{0,0,0,0,0,0}' for sp in sprites)),
            f'alignas(4) static const char MASKS[] =\n{c_string(masks_z)};',
            'static const FaceDef FACE = {"%s", "%s", %d, reinterpret_cast<const uint8_t *>(BG), %d, %d, ROWS, SPRITES, '
            'reinterpret_cast<const uint8_t *>(MASKS), %d, %d, {0x%04x, 0x%04x}, {0x%04x, 0x%04x}};' % (
                fid, meta['name'], size, len(bg_z), len(bg_bytes), len(masks_z), len(masks),
                on['lcd'][0], on['mg'][0], au['lcd'][0], au['mg'][0]),
            '}  // namespace ' + name, '}  // namespace selene', '}  // namespace esphome', '']
        (out_dir / f'{name}.h').write_text('\n'.join(hdr))
        print(f'{fid}: bg {len(bg_bytes)/1024:.0f}->{len(bg_z)/1024:.0f} KiB, masks {len(masks)/1024:.0f}->{len(masks_z)/1024:.0f} KiB, '
              f'sprites {sum(1 for s in sprites if s)}')
        if preview_dir:
            preview(fid, bg565, rows, sprites, masks, on, au, ids, preview_dir, size)
    # registry
    reg = ['#pragma once', '// Generated by tools/pack_faces.py. Do not edit.', '#include "face_types.h"']
    reg += [f'#include "{n}.h"' for _, _, n in names]
    reg += ['namespace esphome {', 'namespace selene {',
            'static const FaceDef *const FACES[] = {%s};' % ', '.join(f'&{n}::FACE' for _, _, n in names),
            f'static constexpr int FACE_COUNT = {len(names)};', '}  // namespace selene', '}  // namespace esphome', '']
    (out_dir / 'faces_all.h').write_text('\n'.join(reg))


def preview(fid, bg565, rows, sprites, masks, on, au, ids, preview_dir, size):
    """Composite a sample lit state exactly like renderer.cpp does (565 math) and save a PNG."""
    preview_dir.mkdir(parents=True, exist_ok=True)
    img = np.zeros((size, size), dtype=np.uint16)
    for y, (x0, n) in enumerate(rows):
        img[y, x0:x0 + n] = bg565[y, x0:x0 + n]
    lit = set()
    import subprocess
    js = ("const M=require('./shared/module.js');let R=5000;const m=new M.Module({tzMin:-300,lat:34.85,lon:-82.39,alarmOn:true,chimeOn:true},{real:()=>R});"
          "const t=Date.UTC(2026,10,24,3,42,37);console.log(JSON.stringify(m.segments(t)))")
    lit = set(json.loads(subprocess.check_output(['node', '-e', js], cwd=Path(__file__).parent.parent)))
    idx = [ids.index(s) for s in lit if s in ids]

    def unpack(c):
        return (((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31)
    rgb = np.stack([((img >> 11) & 31) * 255 // 31, ((img >> 5) & 63) * 255 // 63, (img & 31) * 255 // 31], -1).astype(np.float32)
    for pas in (1, 0):  # aura pass, then body pass
        for i in idx:
            sp = sprites[i]
            if not sp:
                continue
            x, y, w, h, off, cls = sp
            m = np.frombuffer(bytes(masks[off:off + w * h * 2]), dtype=np.uint8).reshape(h, w, 2)[..., pas].astype(np.float32) / 255
            col = np.array(unpack((au if pas else on)['lcd' if cls == 0 else 'mg'][0]), dtype=np.float32)
            region = rgb[y:y + h, x:x + w]
            region[:] = region * (1 - m[..., None]) + col * m[..., None]
    Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8)).save(preview_dir / f'{fid}_preview.png')


if __name__ == '__main__':
    args = sys.argv[1:]
    prev = None
    if '--preview' in args:
        k = args.index('--preview')
        prev = Path(args[k + 1])
        del args[k:k + 2]
    pack(Path(args[0]), Path(args[1]), prev)
